// Generates src/assets/land-mask.ts: which 1° × 1° cells of the Earth are land, one bit per cell.
// The globe on /visitas draws its dots from this mask, so the map data (Natural Earth 1:110m, public domain,
// via the world-atlas package) is only needed here, not in the browser bundle.
//   node scripts/globe/make-land-mask.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topology, topology.objects.land);

const width = 360;
const height = 180;
const bits = new Uint8Array((width * height) / 8);
let count = 0;
// Row 0 is the northernmost band (89°N–90°N); column 0 starts at 180°W.
for (let row = 0; row < height; row++) {
  const latitude = 89.5 - row;
  for (let column = 0; column < width; column++) {
    const longitude = -179.5 + column;
    if (!geoContains(land, [longitude, latitude])) continue;
    const index = row * width + column;
    bits[index >> 3] |= 1 << (index & 7);
    count++;
  }
}

const output = resolve(import.meta.dirname, '../../src/assets/land-mask.ts');
writeFileSync(
  output,
  `// Generated by scripts/globe/make-land-mask.mjs from Natural Earth (public domain). Do not edit.
// ${width} × ${height} cells of 1°; bit (row * ${width} + column) is set for land. Row 0 = 89.5°N, column 0 = 179.5°W.
export const landMask = {
  width: ${width},
  height: ${height},
  bits: '${Buffer.from(bits).toString('base64')}',
};
`,
);
console.log(`${output}: ${count} celdas de tierra de ${width * height}`);
